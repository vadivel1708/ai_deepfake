import os
import io
import csv
import json
from datetime import datetime
from sqlalchemy.orm import Session
from fastapi import HTTPException
from reportlab.lib.pagesizes import letter
from reportlab.lib import colors
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, HRFlowable
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle

from app.models.analysis import AnalysisJob
from app.models.media import MediaRecord
from app.models.review import ReviewRecord
from app.models.user import User


class ReportService:
    @staticmethod
    def generate_csv_report(db: Session, analysis_id: str, current_user: User) -> str:
        job = db.query(AnalysisJob).filter(AnalysisJob.id == analysis_id).first()
        if not job:
            raise HTTPException(status_code=404, detail="Analysis job not found.")

        if job.user_id != current_user.id and current_user.role not in ["reviewer", "admin"]:
            raise HTTPException(status_code=403, detail="Unauthorized to access this report.")

        media = db.query(MediaRecord).filter(MediaRecord.id == job.media_id).first()
        review = db.query(ReviewRecord).filter(ReviewRecord.analysis_id == job.id).first()

        output = io.StringIO()
        writer = csv.writer(output)

        writer.writerow(["AI Forensic Authenticity Analysis Report"])
        writer.writerow(["Generated At", datetime.utcnow().strftime("%Y-%m-%d %H:%M:%S UTC")])
        writer.writerow([])
        writer.writerow(["Metric / Field", "Value"])
        writer.writerow(["Analysis ID", job.id])
        writer.writerow(["Media ID", job.media_id])
        writer.writerow(["Original Filename", media.original_filename if media else "N/A"])
        writer.writerow(["Media Type", media.media_type if media else "N/A"])
        writer.writerow(["Media SHA256", media.sha256_hash if media else "N/A"])
        writer.writerow(["Analysis Status", job.status])
        writer.writerow(["AI Model Name", job.model_name])
        writer.writerow(["AI Model Version", job.model_version])
        writer.writerow(["AI Predicted Class", job.prediction or "N/A"])
        writer.writerow(["Manipulation Likelihood (0.0-1.0)", job.confidence_score if job.confidence_score is not None else "N/A"])
        writer.writerow(["Model Uncertainty (0.0-1.0)", job.uncertainty_score if job.uncertainty_score is not None else "N/A"])
        writer.writerow(["Processing Time (seconds)", job.processing_time_seconds or "N/A"])
        writer.writerow(["Human Reviewer Final Status", review.status if review else "pending_review"])
        writer.writerow(["Reviewer Notes", review.notes if review else "N/A"])
        writer.writerow([])

        # Frame predictions if available
        if job.frame_predictions:
            writer.writerow(["--- Frame-by-Frame Timeline ---"])
            writer.writerow(["Frame Index", "Timestamp (s)", "Manipulation Score", "Is Suspicious", "Face Detected"])
            for fp in job.frame_predictions:
                writer.writerow([fp.frame_index, fp.timestamp_seconds, fp.score, fp.is_suspicious, fp.face_detected])

        writer.writerow([])
        writer.writerow(["LEGAL DISCLAIMER", "This report contains statistical and algorithmic predictions generated by AI forensic models. AI predictions should not be presented as legally conclusive proof of manipulation. A human forensic specialist must independently evaluate results."])

        return output.getvalue()

    @staticmethod
    def generate_pdf_report(db: Session, analysis_id: str, current_user: User) -> io.BytesIO:
        job = db.query(AnalysisJob).filter(AnalysisJob.id == analysis_id).first()
        if not job:
            raise HTTPException(status_code=404, detail="Analysis job not found.")

        if job.user_id != current_user.id and current_user.role not in ["reviewer", "admin"]:
            raise HTTPException(status_code=403, detail="Unauthorized to access this report.")

        media = db.query(MediaRecord).filter(MediaRecord.id == job.media_id).first()
        review = db.query(ReviewRecord).filter(ReviewRecord.analysis_id == job.id).first()

        buffer = io.BytesIO()
        doc = SimpleDocTemplate(
            buffer,
            pagesize=letter,
            rightMargin=40,
            leftMargin=40,
            topMargin=40,
            bottomMargin=40
        )

        styles = getSampleStyleSheet()
        title_style = ParagraphStyle(
            'TitleStyle',
            parent=styles['Heading1'],
            fontSize=18,
            leading=22,
            textColor=colors.HexColor('#0f172a'),
            fontName='Helvetica-Bold'
        )
        subtitle_style = ParagraphStyle(
            'SubtitleStyle',
            parent=styles['Normal'],
            fontSize=10,
            textColor=colors.HexColor('#64748b'),
            leading=14
        )
        section_style = ParagraphStyle(
            'SectionStyle',
            parent=styles['Heading2'],
            fontSize=13,
            leading=16,
            textColor=colors.HexColor('#1e293b'),
            fontName='Helvetica-Bold'
        )
        body_style = ParagraphStyle(
            'Body',
            parent=styles['Normal'],
            fontSize=9,
            leading=13,
            textColor=colors.HexColor('#334155')
        )
        disclaimer_style = ParagraphStyle(
            'Disclaimer',
            parent=styles['Italic'],
            fontSize=8,
            leading=11,
            textColor=colors.HexColor('#b91c1c')
        )

        story = []

        # Header
        story.append(Paragraph("AI Media Authenticity & Deepfake Forensic Report", title_style))
        story.append(Paragraph(f"Generated on {datetime.utcnow().strftime('%Y-%m-%d %H:%M:%S UTC')} | Verification ID: {job.id}", subtitle_style))
        story.append(Spacer(1, 10))
        story.append(HRFlowable(width="100%", thickness=1.5, color=colors.HexColor('#3b82f6'), spaceAfter=15))

        # Media & File Details Table
        story.append(Paragraph("1. Media File Provenance", section_style))
        story.append(Spacer(1, 6))

        file_data = [
            ["Original Filename", media.original_filename if media else "N/A"],
            ["Media Type", (media.media_type if media else "N/A").upper()],
            ["File Size", f"{(media.file_size_bytes / 1024):.1f} KB" if media else "N/A"],
            ["SHA-256 Checksum", media.sha256_hash if media else "N/A"],
            ["Uploaded At", media.created_at.strftime("%Y-%m-%d %H:%M:%S") if media else "N/A"]
        ]
        t1 = Table(file_data, colWidths=[150, 380])
        t1.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (0, -1), colors.HexColor('#f1f5f9')),
            ('TEXTCOLOR', (0, 0), (-1, -1), colors.HexColor('#1e293b')),
            ('FONTNAME', (0, 0), (0, -1), 'Helvetica-Bold'),
            ('FONTSIZE', (0, 0), (-1, -1), 9),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
            ('TOPPADDING', (0, 0), (-1, -1), 4),
            ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#cbd5e1')),
        ]))
        story.append(t1)
        story.append(Spacer(1, 15))

        # AI Prediction Table
        story.append(Paragraph("2. AI Algorithmic Inference Results", section_style))
        story.append(Spacer(1, 6))

        pred_color = '#10b981' if job.prediction == 'likely_authentic' else ('#ef4444' if job.prediction == 'potentially_manipulated' else '#f59e0b')
        conf_str = f"{(job.confidence_score * 100):.1f}%" if job.confidence_score is not None else "N/A"
        uncert_str = f"{(job.uncertainty_score * 100):.1f}%" if job.uncertainty_score is not None else "N/A"

        ai_data = [
            ["Model Pipeline", f"{job.model_name or 'N/A'} (v{job.model_version or '1.0'})"],
            ["AI Classification", (job.prediction or "N/A").replace("_", " ").upper()],
            ["Manipulation Probability", conf_str],
            ["Estimated Uncertainty", uncert_str],
            ["Inference Latency", f"{job.processing_time_seconds or 0:.2f} seconds"],
            ["Recommendations", Paragraph(job.recommendations or "Standard review.", body_style)]
        ]
        t2 = Table(ai_data, colWidths=[150, 380])
        t2.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (0, -1), colors.HexColor('#f8fafc')),
            ('TEXTCOLOR', (0, 0), (-1, -1), colors.HexColor('#1e293b')),
            ('FONTNAME', (0, 0), (0, -1), 'Helvetica-Bold'),
            ('FONTSIZE', (0, 0), (-1, -1), 9),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
            ('TOPPADDING', (0, 0), (-1, -1), 4),
            ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#cbd5e1')),
        ]))
        story.append(t2)
        story.append(Spacer(1, 15))

        # Human Review Status
        story.append(Paragraph("3. Human Forensic Review Determination", section_style))
        story.append(Spacer(1, 6))
        human_status = review.status.replace("_", " ").upper() if review else "PENDING REVIEW"
        review_data = [
            ["Review Status", human_status],
            ["Reviewer Notes", Paragraph(review.notes or "No examiner notes submitted.", body_style) if review else "None"],
            ["Last Status Change", review.updated_at.strftime("%Y-%m-%d %H:%M:%S") if review else "N/A"]
        ]
        t3 = Table(review_data, colWidths=[150, 380])
        t3.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (0, -1), colors.HexColor('#f1f5f9')),
            ('FONTNAME', (0, 0), (0, -1), 'Helvetica-Bold'),
            ('FONTSIZE', (0, 0), (-1, -1), 9),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
            ('TOPPADDING', (0, 0), (-1, -1), 4),
            ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#cbd5e1')),
        ]))
        story.append(t3)
        story.append(Spacer(1, 20))

        # Legal Disclaimer
        story.append(Paragraph("IMPORTANT NOTICE AND SCIENTIFIC DISCLAIMER", ParagraphStyle('DTitle', parent=section_style, fontSize=10, textColor=colors.HexColor('#b91c1c'))))
        story.append(Spacer(1, 4))
        story.append(Paragraph(
            "This report is generated using probabilistic deep learning algorithms and forensic frequency transforms. "
            "AI predictions reflect statistical patterns in image compression, frequency domains, and facial motion. "
            "They do NOT constitute legally conclusive proof of authenticity or manipulation. "
            "Final determinations must be independently verified by certified forensic examiners.",
            disclaimer_style
        ))

        doc.build(story)
        buffer.seek(0)
        return buffer
